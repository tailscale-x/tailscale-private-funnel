#!/usr/bin/env python3
"""Measure maintained source separately from generated output at a Git ref or checkout."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
EXTENSIONS = {
    ".go", ".ts", ".tsx", ".js", ".mjs", ".proto", ".py", ".sh",
    ".css", ".html", ".md", ".yaml", ".yml", ".json",
}


def git(*arguments, binary=False):
    return subprocess.check_output(
        ["git", *arguments], cwd=ROOT, text=not binary
    )


def classify(name, source):
    if name.startswith(("docs/", "README", "PRIVATE_FUNNEL")):
        return "documentation"
    if name.endswith(("_test.go", ".test.ts", ".test.tsx")):
        return "tests"
    if ("Code generated" in source[:1500]
            or name.endswith(("_pb.ts", ".pb.go", ".connect.go", "_templ.go"))
            or name.startswith(("internal/web/assets/", "config/crd/", "config/rbac/", "charts/tailscale-private-funnel/crds/"))
            or "Generated by scripts/generate-operator" in source[:500]):
        return "generated_or_bundled"
    if name.startswith("api/"):
        return "contracts"
    if name.startswith(("scripts/", ".github/")) or name in {"buf.yaml", "buf.gen.yaml"}:
        return "tooling"
    if name.startswith(("ui/", "internal/web/templates/", "internal/web/ui/")):
        return "frontend"
    if name.startswith("internal/provision/"):
        return "provisioning"
    if name.startswith(("internal/manage/", "cmd/")):
        return "cli"
    if name.startswith(("internal/web/", "internal/rpc/")):
        return "server_interface"
    if name in {
        "internal/gateway/control.go", "internal/report/agent.go",
        "internal/kubebroker/client.go",
    }:
        return "clients"
    return "business_and_runtime"


def measure(ref=None):
    arguments = ("ls-tree", "-r", "--name-only", ref) if ref else (
        "ls-files", "--cached", "--others", "--exclude-standard"
    )
    totals = {}
    manual_requests = 0
    for name in sorted(set(git(*arguments).splitlines())):
        path = ROOT / name
        if (path.suffix not in EXTENSIONS
                or name.endswith("package-lock.json")
                or name.startswith("docs/metrics/")
                or (not ref and not path.is_file())):
            continue
        data = git("show", f"{ref}:{name}", binary=True) if ref else path.read_bytes()
        source = data.decode(errors="replace")
        group = classify(name, source)
        item = totals.setdefault(group, {"files": 0, "nonblank_lines": 0, "bytes": 0})
        item["files"] += 1
        item["nonblank_lines"] += sum(bool(line.strip()) for line in source.splitlines())
        item["bytes"] += len(data)
        if group not in {"tests", "generated_or_bundled", "documentation"}:
            manual_requests += len(re.findall(r"http\.NewRequest(?:WithContext)?\(", source))
    return {
        "commit": git("rev-parse", ref or "HEAD").strip(),
        "metric": "UTF-8 source bytes and nonblank source lines",
        "groups": totals,
        "manual_http_request_sites": manual_requests,
        "exclusions": "binary assets, lockfiles, vendored dependencies, build output, measurement output; generated and bundled sources reported separately",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output")
    parser.add_argument("--ref")
    options = parser.parse_args()
    result = json.dumps(measure(options.ref), indent=2, sort_keys=True) + "\n"
    if options.output:
        Path(options.output).write_text(result)
    else:
        print(result, end="")
