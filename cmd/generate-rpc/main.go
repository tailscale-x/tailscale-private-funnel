// Command generate-rpc derives agent documentation from the same descriptors as clients.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/tailscale-x/tailscale-private-funnel/internal/deploymentcli"
	v1 "github.com/tailscale-x/tailscale-private-funnel/internal/gen/funnel/v1"
	"github.com/tailscale-x/tailscale-private-funnel/internal/manage"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

func main() {
	if e := generate(); e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(1)
	}
}
func generate() error {
	b, e := os.ReadFile("internal/rpc/descriptor.bin")
	if e != nil {
		return e
	}
	var set descriptorpb.FileDescriptorSet
	if e = proto.Unmarshal(b, &set); e != nil {
		return e
	}
	registry, e := protodesc.NewFiles(&set)
	if e != nil {
		return e
	}
	services := []protoreflect.ServiceDescriptor{}
	registry.RangeFiles(func(file protoreflect.FileDescriptor) bool {
		if strings.HasPrefix(file.Path(), "funnel/v1/") {
			for i := 0; i < file.Services().Len(); i++ {
				services = append(services, file.Services().Get(i))
			}
		}
		return true
	})
	sort.Slice(services, func(i, j int) bool { return services[i].FullName() < services[j].FullName() })
	var api, cli strings.Builder
	api.WriteString("# Funnel API reference\n\nGenerated from protobuf descriptors. Do not edit.\n\nManagement and Node services use verified Tailscale WhoIs. Enrollment additionally requires one-use proof. Broker methods are served by the installation HTTPS broker with projected Pod tokens, not by control.\n\nSigned payload bytes must never be reserialized before signature verification.\n")
	cli.WriteString("# Funnel CLI\n\nGenerated from protobuf/Cobra metadata. Do not edit.\n\nUse `native` for this Linux machine, `k8s` with an explicit `--context` for operator-backed deployment, and `manage` for the Tailscale-authorized installation API. `native ... create-remote --output script` emits a complete installer for execution on another host. No SSH connection is made by Funnel.\n\nUse `--output json`, mutation `--dry-run`, deployment `--wait` and `--timeout`, and `--yes` for destructive deletion. Instructions are read-only; enrollment starts when create runs. Stop preserves identity and data; delete revokes and removes owned state.\n\nManagement uses `--control-url` or XDG client.json. Secret inputs are file/stdin only. Exit codes: 0 success, 1 failure, 2 invalid input, 3 authorization, 4 transport unavailable, 5 conflict, 6 timeout.\n")
	for _, service := range services {
		fmt.Fprintf(&api, "\n## %s\n\n%s\n", service.FullName(), comments(service))
		for i := 0; i < service.Methods().Len(); i++ {
			m := service.Methods().Get(i)
			permission, _ := proto.GetExtension(m.Options(), v1.E_Permission).(v1.Permission)
			if permission == v1.Permission_PERMISSION_UNSPECIFIED {
				return fmt.Errorf("method lacks permission: %s", m.FullName())
			}
			command, _ := proto.GetExtension(m.Options(), v1.E_Cli).(string)
			fmt.Fprintf(&api, "\n### %s\n\n%s\n\n- RPC: `/%s/%s`\n- Permission: `%s`\n- Input: `%s`\n- Output: `%s`\n", m.Name(), comments(m), service.FullName(), m.Name(), permission, m.Input().FullName(), m.Output().FullName())
			fields(&api, m.Input())
			if payload, _ := proto.GetExtension(m.Options(), v1.E_PayloadType).(string); payload != "" {
				descriptor, err := registry.FindDescriptorByName(protoreflect.FullName(payload))
				if err != nil {
					return fmt.Errorf("unknown signed payload %s: %w", payload, err)
				}
				model, ok := descriptor.(protoreflect.MessageDescriptor)
				if !ok {
					return fmt.Errorf("payload is not a message: %s", payload)
				}
				fmt.Fprintf(&api, "\nSigned payload model: `%s`. Verify exact bytes before decoding.\n", payload)
				fields(&api, model)
			}
			if command != "" {
				fmt.Fprintf(&cli, "\n## manage %s\n\n%s\n\nRequired permission: `%s`. Request: `%s`.\n", command, comments(m), permission, m.Input().FullName())
				fields(&cli, m.Input())
			}
		}
	}
	cli.WriteString("\n# Actual command help\n\nThis section is generated by walking the executable's Cobra management tree.\n")
	root := &cobra.Command{Use: "tailscale-private-funnel"}
	management := &cobra.Command{Use: "manage"}
	manage.Attach(management, nil)
	root.AddCommand(management, deploymentcli.Native("VERSION"), deploymentcli.Kubernetes("VERSION"))
	var walk func(*cobra.Command)
	walk = func(command *cobra.Command) {
		if command.Runnable() {
			command.InitDefaultHelpFlag()
			fmt.Fprintf(&cli, "\n## %s\n\n```text\n%s```\n", command.CommandPath(), command.UsageString())
		}
		for _, child := range command.Commands() {
			walk(child)
		}
	}
	walk(root)
	llms := `# Tailscale Private Funnel

> Tailnet-only management for policy-controlled public HTTP services. Prefer the CLI for agent operations.

## Start here

- [CLI reference](/docs/cli.md): command discovery, authentication, JSON input/output, and actual provisioning.
- [API reference](/docs/api.md): generated RPC methods, request fields and permissions.
- [OpenAPI](/openapi.json): generated Connect HTTP/JSON contract for integrations.
- [Interactive reference](/docs): locally bundled API documentation.

## Agent workflow

1. Run the matching binary's manage --help, then manage whoami and manage health against the selected control URL.
2. Discover resource IDs. Names are display labels, not references.
3. Configure DNS providers and select vendor-discovered zones. Never create DNS records directly through vendor APIs.
4. Preview policy changes and DNS reconciliation. Unmanaged overwrites require explicit approval bound to that exact preview.
5. Use native or k8s component create to execute deployment. Kubernetes always requires an explicit --context. For remote hosts, generate native create-remote --output script and pipe it to your SSH client.
6. Verify identity, fresh reports, backend reachability and public readiness separately. An accepted mutation or generated instruction is not proof of deployment success.

## Security

Management uses WhoIs and configured roles, not bearer tokens or identity headers. Tagged machines do not inherit human Owner/Admin permissions. Do not broaden ACLs automatically. Keep OAuth/provider credentials in protected files or stdin; never in flags, logs or source control. Bootstrap credentials are temporary and returned once. Ordinary restart preserves identity; deployment deletion/revocation is explicit. Public traffic forwarding does not use RPC.
`
	out := "internal/web/assets/api"
	for _, file := range []string{"openapi.json", "node-openapi.json", "broker-openapi.json"} {
		path := filepath.Join(out, file)
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		var document map[string]any
		if err = json.Unmarshal(raw, &document); err != nil {
			return err
		}
		document["info"] = map[string]any{"title": "Tailscale Private Funnel", "version": "v1", "description": "Generated Connect RPC contract. Management and node identity is verified from the Tailscale connection; caller-provided identity headers are never trusted."}
		paths, _ := document["paths"].(map[string]any)
		for _, service := range services {
			for i := 0; i < service.Methods().Len(); i++ {
				method := service.Methods().Get(i)
				entry, _ := paths["/"+string(service.FullName())+"/"+string(method.Name())].(map[string]any)
				if entry == nil {
					continue
				}
				operation, _ := entry["post"].(map[string]any)
				if operation == nil {
					continue
				}
				permission, _ := proto.GetExtension(method.Options(), v1.E_Permission).(v1.Permission)
				command, _ := proto.GetExtension(method.Options(), v1.E_Cli).(string)
				operation["x-funnel-permission"] = strings.TrimPrefix(permission.String(), "PERMISSION_")
				if payload, _ := proto.GetExtension(method.Options(), v1.E_PayloadType).(string); payload != "" {
					operation["x-funnel-signed-payload"] = payload
				}
				audit, _ := proto.GetExtension(method.Options(), v1.E_Audit).(bool)
				operation["x-funnel-audit"] = audit
				if command != "" {
					operation["x-funnel-cli"] = "tailscale-private-funnel manage " + command
				}
				if sensitive, _ := proto.GetExtension(method.Options(), v1.E_Sensitive).(bool); sensitive {
					operation["x-funnel-sensitive"] = true
				}
				description := comments(method)
				if permission == v1.Permission_PERMISSION_BROKER {
					description += "\nRequires installation HTTPS broker TLS and an audience-bound projected Kubernetes token, validated against Pod and node ownership."
				} else {
					description += "\nRequires verified Tailscale WhoIs identity and " + permission.String() + " authorization."
				}
				operation["description"] = strings.TrimSpace(description)
			}
		}
		encoded, err := json.MarshalIndent(document, "", "  ")
		if err != nil {
			return err
		}
		if err = os.WriteFile(path, append(encoded, '\n'), 0644); err != nil {
			return err
		}
	}
	if e = os.MkdirAll(out, 0755); e != nil {
		return e
	}
	for file, body := range map[string]string{"api.md": api.String(), "cli.md": cli.String(), "llms.txt": llms} {
		if e = os.WriteFile(filepath.Join(out, file), []byte(body), 0644); e != nil {
			return e
		}
	}
	return nil
}
func comments(d protoreflect.Descriptor) string {
	return strings.TrimSpace(d.ParentFile().SourceLocations().ByDescriptor(d).LeadingComments)
}
func fields(out *strings.Builder, m protoreflect.MessageDescriptor) {
	if m.Fields().Len() == 0 {
		out.WriteString("\nNo input fields.\n")
		return
	}
	out.WriteString("\n| Field | Type | Notes |\n|---|---|---|\n")
	for i := 0; i < m.Fields().Len(); i++ {
		f := m.Fields().Get(i)
		kind := f.Kind().String()
		if f.Message() != nil {
			kind = string(f.Message().FullName())
		}
		if f.IsMap() {
			kind = "map"
		} else if f.IsList() {
			kind = "list of " + kind
		}
		note := strings.ReplaceAll(comments(f), "\n", " ")
		if secret, _ := proto.GetExtension(f.Options(), v1.E_Secret).(bool); secret {
			note = "Secret; file/stdin only. " + note
		}
		fmt.Fprintf(out, "| `%s` | %s | %s |\n", f.JSONName(), kind, strings.ReplaceAll(note, "|", "\\|"))
	}
}
