// Generate chart RBAC and CR reference from controller-tools output.
package main

import (
	"bytes"
	"fmt"
	"io"
	kyaml "k8s.io/apimachinery/pkg/util/yaml"
	"os"
	"path/filepath"
	"sigs.k8s.io/yaml"
	"sort"
	"strings"
)

func main() {
	b, e := os.ReadFile("config/rbac/role.yaml")
	must(e)
	d := kyaml.NewYAMLOrJSONDecoder(bytes.NewReader(b), 4096)
	out := "# Generated by scripts/generate-operator.sh. Do not edit.\n"
	for {
		var o map[string]any
		e = d.Decode(&o)
		if e == io.EOF {
			break
		}
		must(e)
		if len(o) == 0 {
			continue
		}
		kind := o["kind"].(string)
		rules, e := yaml.Marshal(o["rules"])
		must(e)
		ns := "{{ .Release.Namespace }}"
		name := "{{ .Release.Namespace }}-funnel-operator"
		if kind == "Role" {
			out += "{{- range uniq .Values.managedNamespaces }}\n"
			ns = "{{ . | quote }}"
			name = "tailscale-private-funnel-k8s-operator"
		}
		out += "---\napiVersion: rbac.authorization.k8s.io/v1\nkind: " + kind + "\nmetadata:\n  name: " + name + "\n"
		if kind == "Role" {
			out += "  namespace: " + ns + "\n"
		}
		out += "rules:\n" + string(rules) + "---\napiVersion: rbac.authorization.k8s.io/v1\nkind: " + kind + "Binding\nmetadata:\n  name: " + name + "\n"
		if kind == "Role" {
			out += "  namespace: " + ns + "\n"
		}
		subjectNS := "{{ .Release.Namespace }}"
		if kind == "Role" {
			subjectNS = "{{ $.Release.Namespace }}"
		}
		out += "roleRef: {apiGroup: rbac.authorization.k8s.io, kind: " + kind + ", name: " + name + "}\nsubjects:\n  - {kind: ServiceAccount, name: tailscale-private-funnel-k8s-operator, namespace: " + subjectNS + "}\n"
		if kind == "Role" {
			out += "{{- end }}\n"
		}
	}
	must(os.WriteFile("charts/tailscale-private-funnel/templates/rbac.yaml", []byte(out), 0644))
	docs := "# Kubernetes resource reference\n\nGenerated from the pinned v1alpha1 CRD schemas. Application policy and DNS stay in SQLite.\n\n"
	files, e := filepath.Glob("config/crd/bases/*.yaml")
	must(e)
	for _, file := range files {
		b, e = os.ReadFile(file)
		must(e)
		var crd map[string]any
		must(yaml.Unmarshal(b, &crd))
		spec := crd["spec"].(map[string]any)
		kind := spec["names"].(map[string]any)["kind"].(string)
		docs += "## " + kind + "\n\n| Spec field | Type | Description |\n|---|---|---|\n"
		version := spec["versions"].([]any)[0].(map[string]any)
		props := version["schema"].(map[string]any)["openAPIV3Schema"].(map[string]any)["properties"].(map[string]any)["spec"].(map[string]any)["properties"].(map[string]any)
		keys := []string{}
		for k := range props {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			p := props[k].(map[string]any)
			desc, _ := p["description"].(string)
			docs += fmt.Sprintf("| `%s` | %v | %s |\n", k, p["type"], strings.ReplaceAll(strings.ReplaceAll(desc, "\n", " "), "|", "/"))
		}
		docs += "\n"
	}
	must(os.WriteFile("docs/KUBERNETES_API.md", []byte(docs), 0644))
}
func must(e error) {
	if e != nil {
		panic(e)
	}
}
